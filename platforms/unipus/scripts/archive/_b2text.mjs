import { connect } from "./utlib.mjs";
import fs from "node:fs";
const tabs=await(await fetch("http://127.0.0.1:9222/json/list")).json();
const rd=tabs.find(t=>/ucontent\.unipus\.cn/.test(t.url));
const L=await connect(rd.id);const {ev,frames,cdp}=L;
const tb=(await frames()).find(f=>/textbook\/book/.test(f.url)&&f.ctx);
const t=await ev(`(()=>{const b=[...document.querySelectorAll('div.editor-question-block.questionBlockNode')][2];return (b.innerText||'').replace(/[ ]+/g,' ');})()`,tb.ctx).catch(e=>String(e));
const k=t.lastIndexOf('答案');
const ans=k>=0?t.slice(k+2).trim():'';
fs.writeFileSync('one2.txt',ans);
console.log('len',ans.length,'words',ans.split(/\s+/).length);
console.log('score in block:',(t.match(/得分[^0-9]*([0-9.]+)/)||[])[1]);
