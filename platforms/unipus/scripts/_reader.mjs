import { CDP, sleep } from "./cdp.mjs";
const tabs = await (await fetch("http://127.0.0.1:9222/json/list")).json();
const page = tabs.find(t=>t.type==="page" && /ucontent/.test(t.url));
const cdp = await CDP.connect(page.webSocketDebuggerUrl);
const ev = async (expr) => (await cdp.send("Runtime.evaluate",{expression:expr,returnByValue:true})).result.value;
console.log("FULL URL:\n", await ev("location.href"));
await sleep(4000);
console.log("HASH:", await ev("location.hash"));
console.log("IFRAMES:", JSON.stringify(await ev("[...document.querySelectorAll('iframe')].map(f=>f.src.slice(0,180))")));
cdp.close();
